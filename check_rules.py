#!/usr/bin/env python3
"""
check_rules.py
==============
Re-check rules that are ALREADY on disk, using the current validation logic -
without regenerating anything.

Why this exists: rules generated by earlier versions of the pipeline were never
subjected to the newer checks (UDM field paths, log-source tags, correlation
traps). This sweeps every rule in output/ and reports what would fail today.

Also runs Chronicle's authoritative compile check when CHRONICLE_VERIFY_URL and
CHRONICLE_TOKEN are configured in .env.

Usage:  python check_rules.py [--fix] [--verify] [--limit N] [--recheck]
   --fix       apply deterministic repairs in place (regex suffix flags)
   --verify    submit rules to Chronicle's verifier (needs .env config)
   --limit N   verify at most N rules this run (default 100) - Chronicle has a
               quota, so large libraries need several passes
   --recheck   ignore the cache and re-verify everything

Verification results are cached in .verify_cache.json, keyed by file content.
Re-running --verify only submits rules that are new, changed, or previously
inconclusive (e.g. rate-limited), so you can work through a large library in
several passes without re-spending quota.

Writes check_report.html and check_report.csv.
"""
from __future__ import annotations

import csv
import json
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

# Reuse the generator's logic so the two can never disagree.
try:
    import gap_ruleforge as G
except ImportError:
    sys.exit("Run this from the same folder as gap_ruleforge.py")


def main() -> None:
    do_fix = "--fix" in sys.argv
    do_verify = "--verify" in sys.argv
    recheck = "--recheck" in sys.argv
    limit = 100
    if "--limit" in sys.argv:
        try:
            limit = int(sys.argv[sys.argv.index("--limit") + 1])
        except (IndexError, ValueError):
            sys.exit("--limit needs a number, e.g. --limit 50")

    import hashlib
    cache_path = Path(".verify_cache.json")
    cache: dict[str, dict] = {}
    if cache_path.is_file() and not recheck:
        try:
            cache = json.loads(cache_path.read_text(encoding="utf-8"))
        except Exception:
            cache = {}

    print("Rule checker\n")
    G.LOG_SOURCES = G.load_log_sources()

    out_dir = Path(input("Generated rules folder [output]: ").strip() or "output")
    if not out_dir.is_dir():
        sys.exit(f"Not found: {out_dir}")

    # Newest copy of each filename wins (rules regenerated in later runs).
    newest: dict[str, Path] = {}
    for ext in ("*.yaral", "*.kql"):
        for f in sorted(out_dir.rglob(ext)):
            newest[f.name] = f
    if not newest:
        sys.exit("No rule files found.")
    print(f"  {len(newest)} unique rule file(s)")

    # Pull spec metadata (log_source, platform, rule_type) from run summaries.
    specs: dict[str, dict] = {}
    for s in sorted(out_dir.rglob("run_summary.json")):
        try:
            for r in json.loads(s.read_text(encoding="utf-8")).get("results", []):
                if r.get("file"):
                    specs[r["file"]] = r
        except Exception:
            pass

    if do_verify:
        state = ("ENABLED" if G.chronicle_configured()
                 else "NOT CONFIGURED - skipping")
        print(f"  Chronicle verification: {state}")

    rows = []
    fixed_total = 0
    verified_this_run = 0
    deferred = 0
    for name, path in sorted(newest.items()):
        text = path.read_text(encoding="utf-8", errors="replace")
        lang = "kql" if name.lower().endswith(".kql") else "yaral"
        spec = specs.get(name, {})

        n_fixed = 0
        if lang == "yaral":
            repaired, n_fixed = G.fix_regex_suffix_flags(text)
            if n_fixed and do_fix:
                path.write_text(repaired, encoding="utf-8")
                text = repaired
                fixed_total += n_fixed
            elif n_fixed:
                text = repaired          # check the repaired form, don't save

        warns = G.validate_rule(text, lang, spec or None)

        compiles = None
        detail = ""
        if do_verify and lang == "yaral":
            digest = hashlib.sha256(text.encode("utf-8", "replace")).hexdigest()[:16]
            hit = cache.get(name)
            if hit and hit.get("digest") == digest and hit.get("result") is not None:
                compiles, detail = hit["result"], hit.get("detail", "") + " (cached)"
            elif verified_this_run >= limit:
                compiles, detail = None, "not verified this run (limit reached)"
                deferred += 1
            else:
                compiles, detail = G.chronicle_verify(text)
                verified_this_run += 1
                # Only cache a definite answer; unknowns (quota, network) retry later.
                if compiles is not None:
                    cache[name] = {"digest": digest, "result": compiles,
                                   "detail": detail}
            if compiles is False:
                warns.insert(0, f"CHRONICLE COMPILE FAILED: {detail}")

        # Severity buckets so a reviewer can triage.
        sev = "clean"
        if any(w.startswith("CHRONICLE COMPILE FAILED") for w in warns):
            sev = "compile-error"
        elif any(w.startswith(("INVALID", "BANNED", "UDM:")) for w in warns):
            sev = "must-fix"
        elif any("missing from match block" in w or "chronological" in w for w in warns):
            sev = "must-fix"
        elif warns:
            sev = "review"

        rows.append({
            "file": name,
            "technique": spec.get("id", ""),
            "name": spec.get("name", ""),
            "log_source": spec.get("log_source", ""),
            "platform": spec.get("platform", ""),
            "rule_type": spec.get("rule_type", ""),
            "severity_bucket": sev,
            "auto_fixable": n_fixed,
            "chronicle": {True: "compiles", False: "FAILED", None: ""}[compiles],
            "warning_count": len(warns),
            "warnings": " | ".join(warns),
        })
        mark = {"clean": "OK", "review": "review", "must-fix": "MUST FIX",
                "compile-error": "COMPILE ERROR"}[sev]
        extra = f" [{n_fixed} auto-fixable]" if n_fixed else ""
        print(f"  {mark:<14} {name}{extra}")

    # --- CSV ---
    csv_path = Path("check_report.csv")
    with csv_path.open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    # --- HTML ---
    buckets = Counter(r["severity_bucket"] for r in rows)
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    colour = {"clean": "#4caf50", "review": "#f0ad4e",
              "must-fix": "#d9534f", "compile-error": "#8b0000"}
    trs = "".join(
        f"<tr><td>{r['file']}</td><td>{r['technique']}</td><td>{r['log_source']}</td>"
        f"<td><span style=\"color:{colour[r['severity_bucket']]};font-weight:600\">"
        f"{r['severity_bucket']}</span></td><td>{r['chronicle']}</td>"
        f"<td style=\"font-size:11px\">{r['warnings'][:300]}</td></tr>"
        for r in sorted(rows, key=lambda x: (
            {"compile-error": 0, "must-fix": 1, "review": 2, "clean": 3}[x["severity_bucket"]],
            x["file"])))
    cards = "".join(
        f'<div class="card"><div class="n" style="color:{colour[k]}">{buckets.get(k,0)}</div>'
        f'<div class="l">{k}</div></div>'
        for k in ("compile-error", "must-fix", "review", "clean"))

    html = f"""<!doctype html><html><head><meta charset="utf-8">
<title>Rule check report</title><style>
body{{font-family:-apple-system,Segoe UI,Roboto,sans-serif;margin:0;background:#f4f5f7}}
header{{background:#0a2540;color:#fff;padding:18px 26px}}header h1{{margin:0;font-size:19px}}
.wrap{{padding:18px 26px}} .cards{{display:flex;gap:12px;margin-bottom:14px;flex-wrap:wrap}}
.card{{background:#fff;border:1px solid #e6e8ec;border-radius:10px;padding:12px 18px;min-width:120px}}
.card .n{{font-size:24px;font-weight:700}} .card .l{{font-size:11px;text-transform:uppercase;color:#667}}
table{{width:100%;border-collapse:collapse;background:#fff;font-size:12px;border-radius:8px;overflow:hidden}}
th,td{{padding:7px 10px;text-align:left;border-bottom:1px solid #eef0f2;vertical-align:top}}
th{{background:#f8f9fb;position:sticky;top:0}} .muted{{color:#889;font-size:12px}}
</style></head><body>
<header><h1>Detection rule check report</h1>
<div style="opacity:.75;font-size:13px;margin-top:4px">{len(rows)} rules &middot; {ts}</div></header>
<div class="wrap"><div class="cards">{cards}</div>
<p class="muted">compile-error = Chronicle rejected it &middot; must-fix = invalid syntax,
banned indicator, bad UDM field, or a correlation fault &middot; review = minor
&middot; clean = passed all checks. "UDM-CHECK: unverified" means the field could not be
confirmed offline, not that it is wrong - spot-check those.</p>
<table><tr><th>File</th><th>Technique</th><th>Log source</th><th>Status</th>
<th>Chronicle</th><th>Findings</th></tr>{trs}</table></div></body></html>"""
    Path("check_report.html").write_text(html, encoding="utf-8")

    # Group Chronicle failures by their root cause.
    from collections import Counter as _C
    reasons = _C()
    for r in rows:
        for w in r["warnings"].split(" | "):
            if w.startswith("CHRONICLE COMPILE FAILED"):
                msg = w.split(":", 1)[1].strip()
                if "reference list" in msg:
                    name = msg.split("reference list", 1)[1].split("(")[0].strip()
                    reasons[f"missing reference list: {name}"] += 1
                else:
                    reasons[msg[:90]] += 1
    if reasons:
        print("\n  Chronicle failure reasons:")
        for k, n in reasons.most_common(12):
            print(f"    {n:>4}  {k}")
        missing = sorted({k.split(": ", 1)[1] for k in reasons if k.startswith("missing reference list")})
        if missing:
            print(f"\n  Create these {len(missing)} reference list(s) in Chronicle "
                  f"(empty is fine):")
            for m in missing:
                print(f"    {m}")

    if do_verify and cache:
        cache_path.write_text(json.dumps(cache, indent=1), encoding="utf-8")
        done = len([r for r in rows if r["chronicle"] in ("compiles", "FAILED")])
        print(f"\n  Verified {verified_this_run} this run "
              f"({done}/{len(rows)} have a Chronicle result).")
        if deferred:
            print(f"  {deferred} deferred to stay under the limit - re-run "
                  f"`py check_rules.py --verify` to continue where this left off.")

    print(f"\n  {dict(buckets)}")
    if fixed_total:
        print(f"  Applied {fixed_total} deterministic repair(s) in place.")
    elif any(r["auto_fixable"] for r in rows):
        n = sum(r["auto_fixable"] for r in rows)
        print(f"  {n} issue(s) are auto-fixable - re-run with --fix to apply.")
    print(f"  Wrote check_report.html and check_report.csv")


if __name__ == "__main__":
    main()
